#!/usr/bin/env bash
set -euo pipefail
cd "$(dirname "$0")/.."

[[ $# == 0 || ( $# == 1 && $1 == --clean-tools ) ]] || {
  echo 'Usage: lint-go.sh [--clean-tools]' >&2; exit 1;
}
source tools/lint-tools.sh
trap lint_cache_cleanup EXIT
trap 'exit 130' INT
trap 'exit 143' TERM
lint_cache_begin
# The per-bundle lock also protects running checks from an explicit cache clean.
if [[ ${1:-} == --clean-tools ]]; then
  rm -rf -- "$lint_tools"
  echo "Cleared only pinned lint tool bundle: $lint_key"
  exit 0
fi
lint_prepare_tools
work=$lint_work
bin="$lint_tools/bin"
workspace=$(printf '%s' "$(pwd -P)" | lint_hash)
analysis="$lint_cache/analysis/plaid-v1.0.0-rc.17/$workspace/$(go env GOVERSION)-$lint_platform"
mkdir -p "$analysis"

# Use Go's package selection, not a recursive walk into vendor/testdata.
go list -f '{{.Dir}}' ./... > "$work/packages"
go list -f '{{range .GoFiles}}{{printf "%s/%s\n" $.Dir .}}{{end}}{{range .CgoFiles}}{{printf "%s/%s\n" $.Dir .}}{{end}}{{range .TestGoFiles}}{{printf "%s/%s\n" $.Dir .}}{{end}}{{range .XTestGoFiles}}{{printf "%s/%s\n" $.Dir .}}{{end}}' ./... > "$work/files"
packages=()
files=()
while IFS= read -r path; do [[ -z $path ]] || packages+=("$path"); done < "$work/packages"
while IFS= read -r path; do [[ -z $path ]] || files+=("$path"); done < "$work/files"
# Match the legacy lax generated-comment policy for the formatting companion too.
# Inspect only the header, never marker-like strings in executable code.
import_files=()
for path in "${files[@]}"; do
  header=$(sed -n '/^[[:space:]]*package[[:space:]]/q;p' "$path")
  if grep -Eiq 'code generated|do not edit|autogenerated file|\* generated by: swagger codegen ' <<< "$header"; then
    continue
  else
    search_status=$?
    [[ $search_status == 1 ]] || exit "$search_status"
  fi
  import_files+=("$path")
done
[[ ${#packages[@]} -gt 0 && ${#files[@]} -gt 0 && ${#import_files[@]} -gt 0 ]]
printf 'Go lint: %s packages, %s files including tests, %s non-generated formatting inputs, ' \
  "${#packages[@]}" "${#files[@]}" "${#import_files[@]}"
go version

status=0
echo 'Running plaid-lint'
PLAID_CACHE_DIR="$analysis" "$bin/plaid-lint" run --config .golangci.yml --timeout=3m ./... || status=1
# goimports -l returns zero for formatting differences; both channels must gate.
echo 'Running goimports'
if imports=$("$bin/goimports" -l "${import_files[@]}"); then
  if [[ -n $imports ]]; then printf 'goimports changes required:\n%s\n' "$imports"; status=1; fi
else
  status=1
fi
echo 'Running tenv (all test helpers and compiler checks)'
go vet -vettool="$bin/tenv" -tenv.all=true ./... || status=1

exit "$status"
